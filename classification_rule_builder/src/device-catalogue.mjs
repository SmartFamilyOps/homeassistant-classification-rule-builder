import { automaticCandidateMatches, classifyDevice } from "./rules.mjs";

const text = (value) => String(value ?? "").trim();

export function batteryHealthIncluded(catalogue, classification, device) {
  if (device.battery_monitor) return true;
  if (device.battery_ignore) return false;
  if (classification.source_role === "duplicate") return false;
  if (classification.battery_health === "include") return true;
  if (classification.battery_health === "exclude") return false;
  return automaticCandidateMatches(catalogue, device);
}

export function buildDeviceCatalogue(catalogue, devices) {
  return {
    version: 1,
    generated_at: new Date().toISOString(),
    devices: devices.flatMap((device) => {
      const classification = classifyDevice(catalogue, device);
      if (!batteryHealthIncluded(catalogue, classification, device)) return [];
      return [{
        device_id: text(device.id),
        name: text(device.name) || "Unnamed device",
        manufacturer: text(device.manufacturer) || "Unknown",
        area: text(device.area) || "Unassigned",
        function: classification.function,
        classification: classification.reason,
        matched_rule: classification.rule_name,
        asset_group: classification.asset_group,
        source_role: classification.source_role,
        battery_health: classification.battery_health,
        battery_entity_id: text(device.battery_entity_id),
        entity_ids: [...(device.entity_ids ?? [])],
        relevant_entity_ids: [...(device.relevant_entity_ids ?? [])],
      }];
    }),
  };
}

export function buildDashboardDeviceCatalogues(catalogue, devices, dashboards) {
  return {
    version: 2,
    generated_at: new Date().toISOString(),
    dashboards: dashboards.map((dashboard) => {
      const scopedCatalogue = structuredClone(catalogue);
      scopedCatalogue.dashboard_population = {
        ...(scopedCatalogue.dashboard_population ?? {}),
        automatic_candidates: structuredClone(dashboard.population_policy),
      };
      return {
        dashboard_id: text(dashboard.id),
        title: text(dashboard.title),
        ...buildDeviceCatalogue(scopedCatalogue, devices),
      };
    }),
  };
}

export function validateDeviceCatalogue(candidate) {
  const errors = [];
  if (!candidate || typeof candidate !== "object") return ["Device catalogue must be an object."];
  if (candidate.version !== 1) errors.push("device catalogue version must be 1.");
  if (!Array.isArray(candidate.devices)) errors.push("device catalogue devices must be an array.");
  const ids = new Set();
  for (const [index, device] of (candidate.devices ?? []).entries()) {
    const path = `devices[${index}]`;
    if (!text(device.device_id)) errors.push(`${path}.device_id is required.`);
    else if (ids.has(device.device_id)) errors.push(`${path}.device_id must be unique.`);
    else ids.add(device.device_id);
    if (!text(device.name)) errors.push(`${path}.name is required.`);
    if (!text(device.function)) errors.push(`${path}.function is required.`);
    if (!Array.isArray(device.entity_ids)) errors.push(`${path}.entity_ids must be an array.`);
    if (!Array.isArray(device.relevant_entity_ids)) errors.push(`${path}.relevant_entity_ids must be an array.`);
  }
  return errors;
}

export function validateDashboardDeviceCatalogues(candidate) {
  const errors = [];
  if (!candidate || typeof candidate !== "object") return ["Dashboard device catalogues must be an object."];
  if (candidate.version !== 2) errors.push("dashboard device catalogues version must be 2.");
  if (!Array.isArray(candidate.dashboards) || candidate.dashboards.length === 0) {
    errors.push("dashboard device catalogues must contain at least one dashboard.");
    return errors;
  }
  const ids = new Set();
  for (const [index, dashboard] of candidate.dashboards.entries()) {
    const path = `dashboards[${index}]`;
    if (!text(dashboard.dashboard_id)) errors.push(`${path}.dashboard_id is required.`);
    else if (ids.has(dashboard.dashboard_id)) errors.push(`${path}.dashboard_id must be unique.`);
    else ids.add(dashboard.dashboard_id);
    errors.push(...validateDeviceCatalogue(dashboard).map((error) => `${path}.${error}`));
  }
  return errors;
}

function jinjaValue(value) {
  return JSON.stringify(value).replaceAll("<", "\\u003c");
}

export function generateDeviceCatalogueJinja(deviceCatalogue) {
  const errors = validateDeviceCatalogue(deviceCatalogue);
  if (errors.length) throw new Error(errors.join("\n"));
  return [
    "{# Generated by SmartFamilyOps Discovery Dashboard Builder. Do not edit by hand. #}",
    "{# Refresh discovery and publish in the app to update this installation-specific catalogue. #}",
    "",
    "{% macro battery_health_devices(returns) -%}",
    `  {% do returns(${jinjaValue(deviceCatalogue.devices)}) %}`,
    "{%- endmacro %}",
    "",
  ].join("\n");
}

export function generateDashboardDeviceCataloguesJinja(catalogues) {
  const errors = validateDashboardDeviceCatalogues(catalogues);
  if (errors.length) throw new Error(errors.join("\n"));
  const canonical = catalogues.dashboards.find((dashboard) => dashboard.dashboard_id === "battery-health")
    ?? catalogues.dashboards[0];
  const lines = [
    "{# Generated by SmartFamilyOps Discovery Dashboard Builder. Do not edit by hand. #}",
    "{# Each compatible dashboard has an independent published population. #}",
    "",
    "{% macro dashboard_devices(dashboard_id, returns) -%}",
  ];
  catalogues.dashboards.forEach((dashboard, index) => {
    lines.push(`  {%- ${index === 0 ? "if" : "elif"} dashboard_id == ${jinjaValue(dashboard.dashboard_id)} -%}`);
    lines.push(`    {% do returns(${jinjaValue(dashboard.devices)}) %}`);
  });
  lines.push("  {%- else -%}");
  lines.push("    {% do returns([]) %}");
  lines.push("  {%- endif -%}");
  lines.push("{%- endmacro %}");
  lines.push("");
  lines.push("{% macro battery_health_devices(returns) -%}");
  lines.push(`  {% do returns(${jinjaValue(canonical.devices)}) %}`);
  lines.push("{%- endmacro %}");
  lines.push("");
  return lines.join("\n");
}
